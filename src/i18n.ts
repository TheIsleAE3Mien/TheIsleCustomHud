export function tr(language: AppLanguage, english: string): string {
  return language === "vi" ? VI[english] ?? english : english;
}

export function translatePrimeQuest(language: AppLanguage, quest: string): string {
  if (language !== "vi") return quest;
  const normalized = quest.trim().toLowerCase();
  const migration = normalized.match(/^visit (\d+) migration zones?$/);
  if (migration) return `Ghé ${migration[1]} vùng Di cư`;
  const patrol = normalized.match(/^visit (\d+) patrol zones?$/);
  if (patrol) return `Ghé ${patrol[1]} vùng Tuần tra`;
  return PRIME_QUEST_VI[normalized] ?? quest;
}
